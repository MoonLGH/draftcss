const CARD_VISIBLE_IMAGE_WIDTH = 0.4;

export function getSplashKey(hero) {
  const assetName = hero.splashArt?.split("/").pop()?.replace(/\.[^.]+$/, "");
  return assetName || hero.slug || hero.name?.toLowerCase().replace(/[^a-z0-9]+/g, "-");
}

export function getSplashFocalX(hero, focalPoints = DEFAULT_SPLASH_FOCAL_POINTS) {
  const key = getSplashKey(hero);
  return focalPoints?.[key] ?? DEFAULT_SPLASH_FOCAL_POINTS[key] ?? 0.5;
}

export function getSplashBackgroundPosition(hero, focalPoints = DEFAULT_SPLASH_FOCAL_POINTS) {
  const focalX = getSplashFocalX(hero, focalPoints);
  const maxOffset = 1 - CARD_VISIBLE_IMAGE_WIDTH;
  const positionX = Math.max(0, Math.min(1, (focalX - CARD_VISIBLE_IMAGE_WIDTH / 2) / maxOffset));

  return `${(positionX * 100).toFixed(1)}% bottom`;
}
